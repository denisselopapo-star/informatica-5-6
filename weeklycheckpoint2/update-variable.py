def main():

    # Augmented Assignment Operator

    score=10
    score += 10
    print(score)

    # Substraction Assignment Operator

    #x = x - y
    #x -= y
    score2 = 100
    score2 -= 15
    print(score2)

    # Multiplication Assignment Operator

    score3 = 10
    score3 *=4
    print(score3)

    # Divition Assignment Operator

    x = 10
    x /= 5
    print(int(x))

    # Modulus Assignment Operator

    a = 10
    b = 4
    a %= b
    print(a)





if __name__=="__main__":
    main()
